// internal/infrastructure/ai/openai_service.go
package ai

import (
	"bytes"
	"context"
	"encoding/json"
	"fmt"
	"io"
	"net/http"
	"time"

	"todo-api/internal/domain"
)

const (
	openAIApiURL = "https://api.openai.com/v1/chat/completions"
	model        = "gpt-3.5-turbo" // Veya daha yeni bir model
)

// OpenAIService is an implementation of domain.AIService that uses OpenAI's API.
type OpenAIService struct {
	apiKey     string
	httpClient *http.Client
}

func NewOpenAIService(apiKey string) domain.AIService {
	fmt.Printf("OpenAIService: NewOpenAIService called with apiKey (first 5 chars): '%s'\n", apiKey[:5]) // İlk 5 karakteri gösteriyoruz
	return &OpenAIService{
		apiKey: apiKey,
		httpClient: &http.Client{
			Timeout: 30 * time.Second, // API çağrıları için zaman aşımı
		},
	}
}

// GenerateDescription sends a request to OpenAI's API to generate a description for a todo title.
func (s *OpenAIService) GenerateDescription(ctx context.Context, title string) (string, error) {
	fmt.Printf("AI Service: Entering GenerateDescription for title: '%s'\n", title)

	//fmt.Printf("AI Service: Sending prompt to OpenAI for title: '%s'\n", title) // Bu satır olmalı
	prompt := fmt.Sprintf("Generate a concise and helpful description for a todo item with the title: \"%s\". Keep it under 50 words.", title)

	requestBody, err := json.Marshal(map[string]interface{}{
		"model": model,
		"messages": []map[string]string{
			{"role": "user", "content": prompt},
		},
		"max_tokens":  100, // Maksimum cevap uzunluğu
		"temperature": 0.7, // Yaratıcılık seviyesi
	})
	if err != nil {
		return "", fmt.Errorf("failed to marshal OpenAI request: %w", err)
	}
	fmt.Printf("AI Service: Raw request body: %s\n", string(requestBody)) // Bu satır olmalı

	req, err := http.NewRequestWithContext(ctx, "POST", openAIApiURL, bytes.NewBuffer(requestBody))
	if err != nil {
		return "", fmt.Errorf("failed to create OpenAI request: %w", err)
	}

	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("Authorization", "Bearer "+s.apiKey)

	resp, err := s.httpClient.Do(req)
	if err != nil {
		return "", fmt.Errorf("failed to send request to OpenAI: %w", err)
	}
	defer func() {
		if cerr := resp.Body.Close(); cerr != nil {
			fmt.Printf("Error closing OpenAI response body: %v\n", cerr)
		}
	}()

	if resp.StatusCode != http.StatusOK {
		respBodyBytes, _ := io.ReadAll(resp.Body)
		fmt.Printf("AI Service: OpenAI API returned non-200 status: %d, body: %s\n", resp.StatusCode, string(respBodyBytes)) // Debugging eklendi
		return "", fmt.Errorf("OpenAI API returned non-200 status: %d, body: %s", resp.StatusCode, string(respBodyBytes))
	}

	var openaiResp struct {
		Choices []struct {
			Message struct {
				Content string `json:"content"`
			} `json:"message"`
		} `json:"choices"`
	}

	respBodyBytes, err := io.ReadAll(resp.Body)
	if err != nil {
		return "", fmt.Errorf("failed to read OpenAI response body: %w", err)
	}
	fmt.Printf("AI Service: Raw OpenAI response body: %s\n", string(respBodyBytes)) // Debugging eklendi

	if err := json.Unmarshal(respBodyBytes, &openaiResp); err != nil {
		return "", fmt.Errorf("failed to unmarshal OpenAI response: %w", err)
	}

	if len(openaiResp.Choices) > 0 {
		fmt.Printf("AI Service: Generated description: '%s'\n", openaiResp.Choices[0].Message.Content) // Debugging eklendi
		return openaiResp.Choices[0].Message.Content, nil
	}

	fmt.Println("AI Service: No choices found in OpenAI response.") // Debugging eklendi
	return "", fmt.Errorf("no description generated by OpenAI")
}
